const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');

// Classic scripts work under file://, where fetch and image canvas readback do not.
// Preserve original catalogue coordinates and all conline records without rounding.
const stars = JSON.parse(fs.readFileSync(path.join(root, 'files/BSC.json'), 'utf8'))
    .map((star, index) => [star['harvard_ref_#'] || index, star.RA, star.DEC, star.MAG]);
const constellationFigures = fs.readFileSync(path.join(root, 'files/constellation.figures.txt'), 'utf8')
    .split(/\r?\n/).filter(line => line.startsWith('conline ')).join('\n');
const earthImage = 'data:image/jpeg;base64,' + fs.readFileSync(path.join(root, 'images/spherical-projection-map.jpeg')).toString('base64');
const output = '// Generated by node scripts/build-pole-chart-assets.cjs; edit the source assets, then rebuild.\n'
    + 'globalThis.PSSC_ASSETS = ' + JSON.stringify({ stars, constellationFigures, earthImage }) + ';\n';
fs.writeFileSync(path.join(root, 'pole-shift-star-chart-assets.js'), output);
console.log(`Bundled ${stars.length} catalogue rows, ${constellationFigures.split('\n').length} constellation segments, and Earth texture (${Buffer.byteLength(output)} bytes).`);
